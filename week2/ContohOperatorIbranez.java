public class ContohOperatorIbranez {

    public static void main(String[] args) {
        int a = 60;
        int b = 20;
        int c = 10;

        System.out.println("Aritmatika Operator");
        System.out.println("Bilanagan a adalah = " + a);
        System.out.println("Bilanagan b adalah = " + b);
        System.out.println("Bilanagan c adalah = " + c);
        System.out.println("a + b + c= " + (a + b + c));
        System.out.println("a - b - c= " + (a - b - c));
        System.out.println("a * c= " + (a * c));
        System.out.println("a / c= " + (a / c));
        System.out.println("a % c= " + (a % c));
        System.out.println("a + b * c= " + (a + b * c));
        System.out.println("(a + b) * c= " + ((a + b) * c));

    }
}